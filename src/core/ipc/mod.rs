//! Работа с Unix-сокетами: транспорт и фреймовый протокол.
//!
//! Разбито по файлам:
//! - `socket.rs` — транспорт: `UnixStreamClient` (неблокирующий Unix-сокет,
//!   сырые read/write байт, `peek` через `MSG_PEEK`, `try_clone`, `as_raw_fd`).
//!   Ничего не знает про формат сообщений.
//! - `frame.rs` — фреймовый протокол: `parse_frames` / `build_frame`.
//!   Чистые функции, работают с `&mut Vec<u8>` и `&[u8]`, сокета не касаются.
//!
//! `mod.rs` — реэкспорт и общий лимит `MAX_FRAME`.
//!
//! Здесь НЕТ:
//! - знания о том, что внутри payload (это виджеты и `nsbridge`);
//! - `poll`-цикла (это `app/run.rs`);
//! - решений, когда переподключаться (это `app/bridge.rs`).
//!
//! ## Зачем разделено
//!
//! Раньше `SocketClient` смешивал транспорт и фрейминг: `read_available`
//! знал про «4 байта длины + payload», а `send` — нет, и фрейм собирал
//! вызывающий (дублировалось в `bridge.rs` и `LuaSocket`). Теперь:
//! - транспорт (`UnixStreamClient`) — симметричен: `read_into` / `write_all`
//!   работают с сырыми байтами, протокол снаружи;
//! - фрейминг (`frame`) — чистые функции, тестируются без сокета.
//!
//! ## Формат фрейма
//!
//! 4 байта длины (u32 big-endian) + `len` байт payload. Лимит — `MAX_FRAME`.
//! Фреймы могут прийти частично (TCP-подобная семантика): `parse_frames`
//! возвращает только полностью собранные payload'ы, хвост остаётся в буфере.

pub mod frame;
pub mod socket;

pub use frame::{build_frame, parse_frames, MAX_FRAME};
pub use socket::UnixStreamClient;