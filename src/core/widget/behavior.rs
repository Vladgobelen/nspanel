use std::time::Duration;

use crate::core::ipc::SocketClient;
use crate::core::Rect;
use crate::render::SharedBuffer;

use super::{Action, SizeMode, Theme, WidgetId};

/// Контракт виджета. Панель вызывает эти методы; виджет сам решает,
/// что рисовать, как реагировать на клик/hover и когда просить
/// перерисовку.
///
/// Методы с дефолтной реализацией — опциональны. Обязателен только
/// `render`: виджет, который ничего не рисует, панели не нужен.
pub trait Widget {
    /// Идентификатор = имя папки `widgets/<id>/`.
    fn id(&self) -> WidgetId;

    /// Режим размера. По умолчанию — растянуться по толщине панели.
    fn size_mode(&self) -> SizeMode {
        SizeMode::Stretch { margin: 1, ratio: 2.0 }
    }

    /// Размер `(ширина, высота)` в пикселях. Дефолт считает из `size_mode()`.
    fn preferred_size(&self, panel_thickness: u32, vertical: bool) -> (u32, u32) {
        self.size_mode().preferred_size(panel_thickness, vertical)
    }

    /// Виджет сообщает: «мой `preferred_size` изменился, пересчитай
    /// layout». Панель опрашивает все виджеты после каждого события
    /// (сокет, custom action, update); если хоть один вернул `true` —
    /// пересчитывает `positions` соседей по `side`/`priority`.
    ///
    /// Реализация должна сбросить флаг (one-shot), чтобы повторный
    /// опрос вернул `false`, пока размер снова не изменится.
    ///
    /// Дефолт — `false` (виджет не меняет размер в рантайме).
    fn needs_relayout(&mut self) -> bool {
        false
    }

    /// Нарисовать виджет в буфер. `area` — прямоугольник виджета
    /// **относительно панели** (левый верхний угол = `area.x, area.y`).
    fn render(&self, buf: &SharedBuffer, area: Rect, theme: &Theme);

    /// Клик левой кнопкой по виджету. `x, y` — локальные для виджета.
    /// Возвращает `Action`, панель его исполнит.
    fn on_click(&mut self, _local_x: i32, _local_y: i32) -> Action {
        Action::None
    }

    /// Курсор в точке `(x, y)` относительно виджета.
    /// Возвращает `true`, если виджет изменился (нужна перерисовка).
    /// Виджет САМ решает, что значит "hover" (иконка, график, ...).
    /// Панель зовёт `on_hover(-1, -1)` для сброса, когда курсор ушёл
    /// с панели. Дефолт — `false` (виджет не реагирует на hover).
    fn on_hover(&mut self, _local_x: i32, _local_y: i32) -> bool {
        false
    }

    /// Тултип для точки `(x, y)` относительно виджета.
    ///
    /// Виджет сам решает, что показать. Панель вызывает этот метод
    /// при **изменении** hover (после того как `on_hover` вернул `true`,
    /// или после `clear_hover`). Панель сравнивает результат с текущим
    /// тултипом и показывает/скрывает/обновляет popup.
    ///
    /// `None` — тултипа нет. Дефолт — `None` (виджет не поддерживает
    /// тултипы).
    ///
    /// Включение/выключение тултипа для конкретного виджета — в его
    /// `config.lua` (`tooltip_enabled = true | false`). Панель читает
    /// настройку и, если `false`, не вызывает `tooltip` вообще.
    fn tooltip(&mut self, _local_x: i32, _local_y: i32) -> Option<Vec<String>> {
        None
    }

    /// Пункты контекстного меню (ПКМ по виджету).
    ///
    /// `x, y` — локальные координаты клика (как в `on_click`). Виджет
    /// сам решает, для какого элемента меню строить (например, для
    /// иконки под курсором).
    ///
    /// Каждый пункт — `(label, action)`. Панель показывает меню,
    /// а по выбору исполняет `action`. Дефолт — пустой список.
    fn menu_items(&self, _local_x: i32, _local_y: i32) -> Vec<(String, Action)> {
        Vec::new()
    }

    /// Пользовательское действие из меню.
    ///
    /// Панель вызывает этот метод, когда из меню выбран пункт с
    /// `Action::Custom(msg)`. Виджет сам решает, что делать с `msg`
    /// (например, закрепить/открепить иконку).
    ///
    /// Возвращает `true`, если виджет изменил состояние (нужна перерисовка).
    /// Дефолт — `false` (виджет не обрабатывает кастомные действия).
    fn on_custom_action(&mut self, _msg: &str) -> bool {
        false
    }

    /// Виджет сам говорит, когда его следующий раз будить.
    /// `None` — больше не будить по таймеру (только по событиям).
    fn update(&mut self) -> Option<Duration> {
        None
    }

    /// Дать виджету сокет для чтения данных от внешних демонов (nsbridge, ...).
    /// Панель не знает, что за данные — виджет сам решает.
    fn set_socket(&mut self, _socket: SocketClient) {}

    /// Панель вызывает это, когда в сокете появились данные.
    /// Виджет сам решает, что с ними делать.
    fn on_socket_ready(&mut self) {}
}