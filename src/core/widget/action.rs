/// Действие, которое вернул виджет по клику (или пункт меню).
/// Панель исполняет его сама (лог, запуск команды) или передаёт
/// обратно виджету (`Custom`).
#[derive(Debug, Clone)]
pub enum Action {
    /// Ничего не делать.
    None,
    /// Запустить shell-команду (`sh -c <cmd>`).
    #[allow(dead_code)]
    RunCommand(String),
    /// Залогировать сообщение (отладка).
    Log(String),
    /// Пользовательское действие. Панель передаёт строку обратно
    /// виджету через `Widget::on_custom_action(msg)`. Виджет сам
    /// решает, что делать (например, закрепить/открепить иконку
    /// в таскбаре).
    Custom(String),
}